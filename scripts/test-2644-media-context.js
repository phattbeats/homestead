// PHA-2644 acceptance tests for the media-comprehension package
// (lib/media.js's getMediaContext + extractKeyframes + transcribeAudio).
//
// Drives lib/media.js directly against a temp SQLite + temp DATA_DIR,
// same pattern as scripts/test-media.js. Mounts the comprehension
// route on a fresh in-process express app, drives via http, and
// asserts on the response shape per the issue's Definition of Done.
//
// Test scope (matches PHA-2644 DoD, with pragmatic substitutions
// where ffmpeg/whisper aren't reachable from this CI environment):
//
//   1. Image: upload + GET /api/media/:id/context returns
//      {kind:'image', file, thumb, caption}. The `caption` field is
//      set via the upload form-data text field, then surfaced
//      verbatim by the comprehension package.
//
//   2. Video: upload a synthetic 5-second MP4 with two distinct
//      scenes + a sine-wave audio track. GET /context returns
//      {kind:'video', frames: 3..12 entries, firstFrame, lastFrame,
//      audioTranscript, audioTranscriptStatus, caption}. With no
//      OPENAI_API_KEY and no BYOK header, audioTranscript is null
//      and audioTranscriptStatus === 'no_key'.
//
//   3. Cache hit: second GET /context returns the same payload with
//      cacheHit: true and the same built_at timestamp. mtime on the
//      source file is unchanged.
//
//   4. Bust + rebuild: bustContextCache forces a re-extract; the new
//      payload has cacheHit: false.
//
//   5. Audio-track skip: a near-silent video returns
//      audioTranscriptStatus: 'skipped' without ever calling OpenAI.
//
//   6. Frame serve: GET /api/media-frames/:mediaId/:filename returns
//      200 + non-empty body for an extracted frame.
//
//   7. Soft-delete + cache cascade: removing the media row drops the
//      cache row (ON DELETE CASCADE).

'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');
const { execFile } = require('child_process');
const { promisify } = require('util');
const Database = require('better-sqlite3');

const execFileP = promisify(execFile);

let pass = 0;
let fail = 0;
function ok(label) { pass++; console.log(`  ✓ ${label}`); }
function ng(label, detail) { fail++; console.log(`  ✗ ${label}${detail ? ` — ${detail}` : ''}`); }
function assert(cond, label, detail) { if (cond) ok(label); else ng(label, detail); }
function assertEq(actual, expected, label) {
  const a = JSON.stringify(actual), e = JSON.stringify(expected);
  if (a === e) ok(label); else ng(label, `expected ${e}, got ${a}`);
}

const PNG_1X1 = Buffer.from(
  'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=',
  'base64'
);

console.log('PHA-2644 media-context tests\n');

// Generate a synthetic 5-second MP4 with two distinct visual scenes
// (color→color) and a 440Hz sine-wave audio track. Used by tests 2
// and 5. The 5s length gives the scene-change selector enough
// material to find at least one cut; the audio gives whisper-class
// ASR something to transcribe (in test 5 we make it silent instead).
async function makeTestVideo({ duration = 5, sceneAt = 2, silent = false } = {}) {
  // 2-segment concat: blue 0..2s, then red 2..5s. Each segment is
  // generated by lavfi's `color` source with a forced duration. The
  // concat filter stitches them.
  const seg1Dur = sceneAt;
  const seg2Dur = duration - sceneAt;
  const filter = silent
    ? `[0:v]format=yuv420p[v0];[1:v]format=yuv420p[v1];[v0][v1]concat=n=2:v=1:a=0[outv]`
    : `[0:v]format=yuv420p[v0];[1:v]format=yuv420p[v1];[v0][v1]concat=n=2:v=1:a=0[outv];[2:a]aresample=16000:resampler=soxr,pan=mono|c0=c0[mono]`;
  const outTmp = path.join(os.tmpdir(), `homestead-test-video-${crypto.randomUUID()}.mp4`);
  const args = silent
    ? [
        '-y',
        '-f', 'lavfi', '-i', `color=c=blue:s=320x240:r=15:d=${seg1Dur}`,
        '-f', 'lavfi', '-i', `color=c=red:s=320x240:r=15:d=${seg2Dur}`,
        '-filter_complex', filter,
        '-map', '[outv]',
        '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-preset', 'ultrafast',
        '-movflags', '+faststart',
        '-f', 'mp4',
        outTmp,
      ]
    : [
        '-y',
        '-f', 'lavfi', '-i', `color=c=blue:s=320x240:r=15:d=${seg1Dur}`,
        '-f', 'lavfi', '-i', `color=c=red:s=320x240:r=15:d=${seg2Dur}`,
        '-f', 'lavfi', '-i', `sine=frequency=440:duration=${duration}`,
        '-filter_complex', filter,
        '-map', '[outv]', '-map', '[mono]',
        '-c:v', 'libx264', '-pix_fmt', 'yuv420p', '-preset', 'ultrafast',
        '-c:a', 'aac', '-b:a', '64k',
        '-shortest',
        '-movflags', '+faststart',
        '-f', 'mp4',
        outTmp,
      ];
  const { execFile } = require('child_process');
  return new Promise((resolve, reject) => {
    execFile('ffmpeg', args, { encoding: 'buffer', maxBuffer: 32 * 1024 * 1024 }, (err, stdout, stderr) => {
      if (err) {
        try { fs.unlinkSync(outTmp); } catch (_) { /* */ }
        return reject(new Error(`ffmpeg video synth failed: ${err.message}\n${stderr ? stderr.toString().slice(0, 400) : ''}`));
      }
      // MP4 muxer needs a seekable output, so we wrote to a temp
      // file. Read it back and unlink.
      const buf = fs.readFileSync(outTmp);
      try { fs.unlinkSync(outTmp); } catch (_) { /* */ }
      resolve(buf);
    });
  });
}

(async () => {
  const tmpDataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'homestead-media-context-test-'));
  process.env.DATA_DIR = tmpDataDir;
  // Ensure no stray server-staged key is consulted during the
  // no-key path tests.
  delete process.env.OPENAI_API_KEY;

  const userModel = require('../lib/user-model');
  const media = require('../lib/media');
  const analytics = require('../lib/analytics');

  const dbPath = path.join(tmpDataDir, 'life.db');
  const db = new Database(dbPath);
  userModel.migrate(db);
  media.migrate(db);
  analytics.migrate(db);

  const brandon = db.prepare('SELECT id FROM users WHERE username = ?').get('brandon');

  // In-process express server mounting the comprehension route,
  // frames-serve route, and the original PHA-2149 routes so the
  // same upload flow that production uses is exercised.
  const app = require('express')();
  app.use((req, res, next) => {
    req.session = { user: { username: 'brandon' } };
    next();
  });
  app.post('/api/media', media.upload);
  app.get('/api/media/:id', (req, res) => media.fetch(req.params.id, res, false));
  app.get('/api/media/:id/thumb', (req, res) => media.fetch(req.params.id, res, true));
  app.get('/api/media/:id/context', media.getMediaContext);
  // Reuse the same frames-serve logic as server.js; reimplemented
  // here so the test owns its routing.
  const framesDir = path.join(tmpDataDir, 'media-frames');
  app.get('/api/media-frames/:mediaId/:filename', (req, res) => {
    const seg = (s) => s.includes('..') || s.includes('/') || s.includes('\\');
    if (seg(req.params.mediaId) || seg(req.params.filename)) return res.status(400).json({ error: 'invalid' });
    const dir = path.join(framesDir, req.params.mediaId);
    const abs = path.join(dir, req.params.filename);
    if (!abs.startsWith(dir + path.sep)) return res.status(400).json({ error: 'invalid path' });
    if (!fs.existsSync(abs)) return res.status(404).json({ error: 'not found' });
    res.sendFile(abs);
  });

  const server = await new Promise((resolve) => {
    const s = app.listen(0, '127.0.0.1', () => resolve(s));
  });
  const port = server.address().port;
  const base = `http://127.0.0.1:${port}`;

  function multipartBody(fields) {
    // fields: [{ name, filename?, mime?, value (string|Buffer) }]
    const boundary = '----homestead-2644-boundary';
    const parts = [];
    for (const f of fields) {
      const head = f.filename
        ? `--${boundary}\r\nContent-Disposition: form-data; name="${f.name}"; filename="${f.filename}"\r\nContent-Type: ${f.mime}\r\n\r\n`
        : `--${boundary}\r\nContent-Disposition: form-data; name="${f.name}"\r\n\r\n`;
      parts.push(Buffer.from(head));
      parts.push(Buffer.isBuffer(f.value) ? f.value : Buffer.from(String(f.value)));
      parts.push(Buffer.from('\r\n'));
    }
    parts.push(Buffer.from(`--${boundary}--\r\n`));
    return { boundary, body: Buffer.concat(parts) };
  }

  async function upload(fields) {
    const { boundary, body } = multipartBody(fields);
    const res = await fetch(`${base}/api/media`, {
      method: 'POST',
      headers: { 'Content-Type': `multipart/form-data; boundary=${boundary}` },
      body,
    });
    return { status: res.status, json: await res.json() };
  }

  async function getContext(id, byokKey) {
    const headers = {};
    if (byokKey) headers['X-Whisper-Key'] = byokKey;
    const res = await fetch(`${base}/api/media/${id}/context`, { headers });
    return { status: res.status, json: await res.json() };
  }

  // ---- Test 1: image comprehension ----
  console.log('\nTest 1: image comprehension');
  const up1 = await upload([
    { name: 'file', filename: 'captioned.png', mime: 'image/png', value: PNG_1X1 },
    { name: 'caption', value: 'a 1x1 transparent test pixel' },
  ]);
  assertEq(up1.status, 200, 'image upload returns 200');
  assertEq(up1.json.kind, 'image', 'kind=image');
  assertEq(up1.json.caption, 'a 1x1 transparent test pixel', 'caption surfaced via publicView');

  const ctx1 = await getContext(up1.json.id);
  assertEq(ctx1.status, 200, 'image context returns 200');
  assertEq(ctx1.json.kind, 'image', 'context kind=image');
  assertEq(ctx1.json.caption, 'a 1x1 transparent test pixel', 'context surfaces caption');
  assert(ctx1.json.file && ctx1.json.file.includes(up1.json.id), 'context.file references media id');
  assert(ctx1.json.thumb && ctx1.json.thumb.includes('/thumb'), 'context.thumb is the thumb URL');
  assertEq(ctx1.json.frames, [], 'image has no frames');
  assertEq(ctx1.json.cacheHit, false, 'first call is a cache miss');
  assert(ctx1.json.cachedAt === null, 'first call has no cachedAt');

  // ---- Test 2: video comprehension (no key) ----
  console.log('\nTest 2: video comprehension (no whisper key)');
  const videoBuf = await makeTestVideo({ duration: 5, sceneAt: 2, silent: false });
  const up2 = await upload([
    { name: 'file', filename: 'scene-change.mp4', mime: 'video/mp4', value: videoBuf },
    { name: 'caption', value: 'blue→red scene cut with a 440Hz tone' },
  ]);
  assertEq(up2.status, 200, 'video upload returns 200');
  assertEq(up2.json.kind, 'video', 'kind=video');
  assert(up2.json.durationMs >= 4000, `duration probed (got ${up2.json.durationMs}ms)`);
  assert(up2.json.width === 320, `width probed (got ${up2.json.width})`);

  const ctx2 = await getContext(up2.json.id);
  assertEq(ctx2.status, 200, 'video context returns 200');
  assertEq(ctx2.json.kind, 'video', 'context kind=video');
  assert(ctx2.json.frames.length >= 3 && ctx2.json.frames.length <= 12,
    `frame count 3..12 (got ${ctx2.json.frames.length})`);
  assert(ctx2.json.firstFrame && ctx2.json.frames[0].url === ctx2.json.firstFrame,
    'firstFrame === frames[0].url');
  assert(ctx2.json.lastFrame && ctx2.json.frames[ctx2.json.frames.length - 1].url === ctx2.json.lastFrame,
    'lastFrame === frames[-1].url');
  for (const f of ctx2.json.frames) {
    assert(f.url.startsWith('/api/media-frames/'), `frame url is well-formed: ${f.url}`);
    assert(Number.isInteger(f.index) && f.index >= 1, `frame.index is positive int (got ${f.index})`);
  }
  assertEq(ctx2.json.audioTranscript, null, 'no key → audioTranscript null');
  assertEq(ctx2.json.audioTranscriptStatus, 'no_key', 'no key → audioTranscriptStatus no_key');
  assertEq(ctx2.json.caption, 'blue→red scene cut with a 440Hz tone', 'video caption surfaced');

  // Frame serve: pick frame 1, fetch it, expect 200 + non-empty body.
  const frameUrl = ctx2.json.frames[0].url;
  const frameFetch = await fetch(`${base}${frameUrl}`);
  assertEq(frameFetch.status, 200, 'frame serve returns 200');
  const frameBody = Buffer.from(await frameFetch.arrayBuffer());
  assert(frameBody.length > 0, 'frame body is non-empty');
  // JPGs start with FF D8 FF.
  assert(frameBody[0] === 0xFF && frameBody[1] === 0xD8 && frameBody[2] === 0xFF,
    'frame body starts with JPG magic bytes');

  // ---- Test 3: cache hit on second call ----
  console.log('\nTest 3: cache hit on second call');
  const srcPath = path.join(tmpDataDir, db.prepare('SELECT path FROM media_uploads WHERE id = ?').get(up2.json.id).path);
  const mtimeBefore = fs.statSync(srcPath).mtimeMs;
  // The cache row was written during the first call (test 2); its
  // built_at is the canonical timestamp that a cache hit should
  // surface. The first call's response has cachedAt: null because
  // the payload is fresh; the second call's cachedAt is the
  // built_at from when the cache row was written.
  const cacheRow = db.prepare('SELECT built_at FROM media_context_cache WHERE media_id = ?').get(up2.json.id);
  const ctx2b = await getContext(up2.json.id);
  const mtimeAfter = fs.statSync(srcPath).mtimeMs;
  assertEq(ctx2b.status, 200, 'second call returns 200');
  assertEq(ctx2b.json.cacheHit, true, 'second call is a cache hit');
  assertEq(ctx2b.json.cachedAt, cacheRow.built_at, 'cachedAt matches the cache row built_at');
  // Verify mtime unchanged — the comprehension should not re-write
  // the source file.
  assertEq(mtimeAfter, mtimeBefore, 'source mtime unchanged across cache hit');

  // ---- Test 4: bust + rebuild ----
  console.log('\nTest 4: bustContextCache + rebuild');
  const dropped = media.bustContextCache(up2.json.id);
  assertEq(dropped, 1, 'bust drops 1 cache row');
  const ctx2c = await getContext(up2.json.id);
  assertEq(ctx2c.status, 200, 'rebuilt context returns 200');
  assertEq(ctx2c.json.cacheHit, false, 'rebuilt context is a cache miss');
  assert(ctx2c.json.frames.length >= 3 && ctx2c.json.frames.length <= 12, 'rebuilt frames still in range');

  // ---- Test 5: silent video → transcript skipped ----
  console.log('\nTest 5: silent video → audioTranscriptStatus=skipped');
  // Provide a fake BYOK so transcribeAudio reaches the file-size
  // check rather than the no_key path. We never actually call
  // OpenAI; the test only verifies the cheap-skip branch fires
  // BEFORE the HTTP request.
  const silentBuf = await makeTestVideo({ duration: 2, sceneAt: 1, silent: true });
  const up5 = await upload([
    { name: 'file', filename: 'silent.mp4', mime: 'video/mp4', value: silentBuf },
  ]);
  assertEq(up5.status, 200, 'silent video upload returns 200');
  const ctx5 = await getContext(up5.json.id, 'sk-fake-byok-do-not-call');
  assertEq(ctx5.status, 200, 'silent context returns 200');
  assertEq(ctx5.json.audioTranscript, null, 'silent video: audioTranscript null');
  assertEq(ctx5.json.audioTranscriptStatus, 'skipped',
    `silent video: status=skipped (got ${ctx5.json.audioTranscriptStatus})`);

  // ---- Test 6: soft-delete + cache cascade ----
  console.log('\nTest 6: soft-delete + cache cascade');
  const cacheBefore = db.prepare('SELECT COUNT(*) c FROM media_context_cache WHERE media_id = ?').get(up1.json.id).c;
  assertEq(cacheBefore, 1, 'image cache row present before delete');
  const removed = media.remove(up1.json.id, brandon.id);
  assertEq(removed.ok, true, 'owner can soft-delete image');
  const cacheAfter = db.prepare('SELECT COUNT(*) c FROM media_context_cache WHERE media_id = ?').get(up1.json.id).c;
  assertEq(cacheAfter, 0, 'cache row dropped on soft-delete');
  const ctx1After = await getContext(up1.json.id);
  assertEq(ctx1After.status, 404, 'context on soft-deleted media returns 404');

  // ---- Test 7: migration adds caption column to pre-existing row ----
  // (Spawns a child Node process so the module-level _db doesn't
  // get rebound mid-test. Cheap, isolated, and avoids a require-
  // cache hack.)
  console.log('\nTest 7: caption column migration (child process)');
  const legacyScript = `
    const path = require('path');
    const fs = require('fs');
    const os = require('os');
    const Database = require('better-sqlite3');
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'homestead-media-legacy-'));
    const db = new Database(path.join(dir, 'legacy.db'));
    db.exec(\`CREATE TABLE media_uploads (
      id TEXT PRIMARY KEY, owner_user_id INTEGER NOT NULL,
      kind TEXT NOT NULL CHECK(kind IN ('image','video')),
      mime TEXT NOT NULL, bytes INTEGER NOT NULL,
      original_name TEXT, width INTEGER, height INTEGER,
      duration_ms INTEGER, sha256 TEXT NOT NULL, path TEXT NOT NULL,
      thumb_path TEXT, poster_path TEXT, expires_at TEXT,
      deleted_at TEXT, created_at TEXT NOT NULL DEFAULT (datetime('now'))
    );\`);
    db.prepare(\`INSERT INTO media_uploads
      (id, owner_user_id, kind, mime, bytes, sha256, path)
      VALUES ('legacy-id', 1, 'image', 'image/png', 42, 'deadbeef', 'legacy/path')\`).run();
    process.env.DATA_DIR = dir;
    const media = require(${JSON.stringify(path.resolve(__dirname, '../lib/media.js'))});
    media.migrate(db);
    const cols = db.prepare('PRAGMA table_info(media_uploads)').all().map((c) => c.name);
    const row = db.prepare('SELECT * FROM media_uploads WHERE id = ?').get('legacy-id');
    console.log(JSON.stringify({ ok: cols.includes('caption'), rowPreserved: !!row, captionNull: row && row.caption === null, cols }));
  `;
  const child = require('child_process').spawnSync('node', ['-e', legacyScript], { encoding: 'utf8' });
  if (child.status !== 0) {
    ng('migration child process', `exit ${child.status}: ${child.stderr}`);
  } else {
    let parsed;
    try { parsed = JSON.parse(child.stdout.trim().split('\n').pop()); }
    catch (e) { ng('migration child process parse', e.message); }
    if (parsed) {
      assert(parsed.ok, 'caption column added via ALTER TABLE');
      assert(parsed.rowPreserved, 'legacy row preserved through migration');
      assert(parsed.captionNull, 'legacy row caption defaults to null');
    }
  }

  await new Promise((resolve) => server.close(resolve));

  console.log(`\n${pass} passed, ${fail} failed`);
  process.exit(fail > 0 ? 1 : 0);
})().catch((e) => {
  console.error('FATAL:', e);
  process.exit(1);
});
